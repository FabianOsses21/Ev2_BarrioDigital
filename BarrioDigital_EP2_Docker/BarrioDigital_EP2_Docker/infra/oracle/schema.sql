-- BarrioDigital — DDL Oracle para cada esquema.
-- Ejecutar cada bloque conectado como el usuario dueño del esquema.
-- Los nombres de columna siguen la estrategia física de Spring Boot
-- (camelCase -> snake_case), requerido por spring.jpa.hibernate.ddl-auto=validate.

-- ============ ESQUEMA CATALOG (ORACLE_CATALOG_USER) ============

CREATE TABLE tipos_tramite (
    id           VARCHAR2(64 CHAR)  NOT NULL,
    nombre       VARCHAR2(120 CHAR) NOT NULL,
    descripcion  VARCHAR2(500 CHAR) NOT NULL,
    cupo_diario  NUMBER(10,0)       NOT NULL,
    activo       NUMBER(1,0)        NOT NULL,
    CONSTRAINT pk_tipos_tramite PRIMARY KEY (id)
);

-- El catálogo se siembra solo al primer arranque (CommandLineRunner
-- inserta los 3 tipos si la tabla está vacía). No agregar seeds aquí.

-- ============ ESQUEMA REQUESTS (ORACLE_REQUESTS_USER) ============

CREATE TABLE tramites_pedidos (
    id                  VARCHAR2(64 CHAR)  NOT NULL,
    tipo_id             VARCHAR2(64 CHAR)  NOT NULL,
    tipo_nombre         VARCHAR2(120 CHAR) NOT NULL,
    asunto              VARCHAR2(150 CHAR) NOT NULL,
    descripcion         VARCHAR2(1000 CHAR) NOT NULL,
    propietario_id      VARCHAR2(64 CHAR)  NOT NULL,
    propietario_nombre  VARCHAR2(150 CHAR) NOT NULL,
    cliente_email       VARCHAR2(150 CHAR),
    estado              VARCHAR2(30 CHAR)  NOT NULL,
    fecha_creacion      TIMESTAMP          NOT NULL,
    fecha_actualizacion TIMESTAMP          NOT NULL,
    fecha_admision      TIMESTAMP,
    version             NUMBER(19,0),
    CONSTRAINT pk_tramites_pedidos PRIMARY KEY (id)
);

CREATE TABLE items_pedido (
    id              NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre          VARCHAR2(150 CHAR) NOT NULL,
    cantidad        NUMBER(10,0)       NOT NULL,
    precio_unitario NUMBER(12,2),
    tramite_id      VARCHAR2(64 CHAR),
    CONSTRAINT pk_items_pedido PRIMARY KEY (id),
    CONSTRAINT fk_items_tramite FOREIGN KEY (tramite_id)
        REFERENCES tramites_pedidos (id)
);

CREATE TABLE tramite_write_lock (
    id NUMBER(19,0) NOT NULL,
    CONSTRAINT pk_tramite_write_lock PRIMARY KEY (id)
);

